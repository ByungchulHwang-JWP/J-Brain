#!/bin/bash
# =============================================================================
# 사내 지식 챗봇 플랫폼 - 서비스 상태 확인 스크립트
# =============================================================================

echo "==========================================="
echo "  서비스 상태 확인"
echo "==========================================="

# 백엔드 상태 확인
echo ""
echo "🔌 백엔드 API 서버 (포트 8080):"
BACKEND=$(lsof -ti:8080)
if [ -n "$BACKEND" ]; then
    echo "   ✅ 실행 중 (PID: $BACKEND)"
    echo "   URL: http://127.0.0.1:8080"
    echo "   API 문서: http://127.0.0.1:8080/docs"
else
    echo "   ❌ 중지됨"
fi

# 프론트엔드 상태 확인
echo ""
echo "🌐 프론트엔드(FO) 서버 (포트 5174):"
FRONTEND=$(lsof -ti:5174)
if [ -n "$FRONTEND" ]; then
    echo "   ✅ 실행 중 (PID: $FRONTEND)"
    echo "   URL: http://localhost:5174"
else
    echo "   ❌ 중지됨"
fi

echo ""
echo "==========================================="
